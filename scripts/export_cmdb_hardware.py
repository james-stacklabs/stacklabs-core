def fetch_hardware_inventory():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()
    
    query = """
        WITH RankedHardware AS (
            SELECT 
                c.sys_id,
                c.name as node_name,
                c.short_description,
                c.operational_status,
                c.assigned_to,
                h.ip_address,
                h.mac_address,
                h.model_id,
                h.u_avatar_url,
                c.sys_created_on,
                c.sys_updated_on,
                ROW_NUMBER() OVER (
                    PARTITION BY c.name 
                    ORDER BY 
                        CASE WHEN c.sys_id LIKE 'hw_%' THEN 1 ELSE 2 END,
                        CASE WHEN h.model_id IS NOT NULL AND h.model_id != '' THEN 1 ELSE 2 END,
                        c.sys_updated_on DESC
                ) as rn
            FROM cmdb_ci c
            JOIN cmdb_ci_hardware h ON c.sys_id = h.sys_id
            WHERE c.sys_class_name = 'cmdb_ci_hardware'
        )
        SELECT 
            sys_id, node_name, short_description, operational_status, assigned_to,
            ip_address, mac_address, model_id, u_avatar_url, sys_created_on, sys_updated_on
        FROM RankedHardware
        WHERE rn = 1
        ORDER BY 
            CASE 
                WHEN node_name IN ('clio', 'artemis', 'pegasus', 'beelink') THEN 1
                WHEN node_name IN ('mando', 'argo', 'calvin', 'hobbes', 'metsy-prime') THEN 2
                WHEN node_name LIKE '%grogu%' OR node_name LIKE '%stumpy%' OR node_name LIKE '%mobile%' THEN 3
                WHEN node_name LIKE '%cam%' OR node_name LIKE '%mic%' OR node_name LIKE '%webcam%' THEN 4
                WHEN node_name LIKE '%pixel%' OR node_name LIKE '%ipad%' OR node_name LIKE '%s23%' THEN 5
                ELSE 6
            END,
            node_name ASC
    """
    rows = cur.execute(query).fetchall()
    conn.close()
    return [dict(r) for r in rows]

