#!/home/james/stacklabs/.venv/bin/python3
"""
StackLabs 2-Tier Hybrid Acoustic Transcriber & Entity Alignment Engine
Tier 1: Heavy acoustic lifting on Artemis (100.108.185.53) GTX 1060 CUDA Faster-Whisper ($0.00).
Tier 2: Semantic entity correction & homophone alignment via gemini-3.8-flash ($0.0004).
"""
import os
import sys
import time
import argparse
import subprocess
from pathlib import Path
from dotenv import load_dotenv

REPO_ROOT = Path("/home/james/stacklabs")
load_dotenv(REPO_ROOT / ".env")

# Canonical StackLabs Domain Glossary & Homophone Corrections
DEFAULT_DOMAIN_GLOSSARY = {
    "Pawel Rudnicki": "Horizon dealmaker and check-writer (often misheard phonetically as Paul Radnicki or Pavel)",
    "SOX": "Sarbanes-Oxley corporate and accounting governance compliance (not socks or Sox)",
    "POSIX VFS": "POSIX Virtual File System in user space (not pause X, BFF, or VFX)",
    "SQLite WAL": "SQLite Write-Ahead Logging mode (not SQLite wall)",
    "ServiceNow CMDB": "Configuration Management Database (not CMD B or CMD-B)",
    "sys_id": "ServiceNow 32-character hexadecimal identifier (not SIS ID or six id)",
    "CI": "Configuration Item in CMDB (not see eye or see-I)",
    "ALU": "Arithmetic Logic Unit (not Alu, A LU, or alloy)",
    "GBNF": "GGML BNF grammar clamping notation (not GBN, GB and F)",
    "Statcast": "MLB optical ball-tracking radar (not stat cast or static)",
    "AmFam Field": "American Family Field, Milwaukee (not am fam or Aunt Fam)",
    "Brewers": "Milwaukee Brewers baseball franchise",
    "Clio": "Workstation local forge hub (not Cleo)",
    "Artemis": "Dedicated GPU transcription host with GTX 1060 silicon",
    "TTR": "Time to Resolution / Time to Reflex",
    "EBITDA": "Earnings Before Interest, Taxes, Depreciation, and Amortization"
}

def run_tier1_whisper(audio_path: Path, raw_output_path: Path, model: str = "base.en", compute: str = "int8_float32") -> bool:
    """Dispatches audio transcription to Artemis CUDA Faster-Whisper."""
    dispatcher = REPO_ROOT / "scripts" / "transcribe_on_artemis.py"
    if not dispatcher.exists():
        print(f"Error: Dispatcher script not found: {dispatcher}", file=sys.stderr)
        return False

    cmd = [
        str(REPO_ROOT / ".venv" / "bin" / "python3"),
        str(dispatcher),
        str(audio_path),
        "--output", str(raw_output_path),
        "--model", model,
        "--compute", compute
    ]

    print("\n" + "=" * 70)
    print("⚡ TIER 1: ARTEMIS CUDA ACOUSTIC LIFTING ($0.00)")
    print("=" * 70)
    res = subprocess.run(cmd)
    return res.returncode == 0 and raw_output_path.exists() and raw_output_path.stat().st_size > 0

def run_tier2_semantic_alignment(raw_transcript_path: Path, aligned_output_path: Path, glossary: dict = None) -> bool:
    """Sends text transcript to gemini-3.8-flash for semantic entity and homophone correction."""
    if glossary is None:
        glossary = DEFAULT_DOMAIN_GLOSSARY

    raw_text = raw_transcript_path.read_text(encoding="utf-8")
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        print("⚠️ Warning: GEMINI_API_KEY not found in environment. Skipping Tier 2 alignment.")
        aligned_output_path.write_text(raw_text, encoding="utf-8")
        return False

    print("\n" + "=" * 70)
    print("🧠 TIER 2: GEMINI 3.8 FLASH SEMANTIC ALIGNMENT (~$0.0004)")
    print("=" * 70)

    try:
        from google import genai
        client = genai.Client(api_key=api_key)

        glossary_items = "\n".join([f"- **{k}**: {v}" for k, v in glossary.items()])
        prompt = f"""You are an authoritative domain editor and semantic alignment engine for StackLabs LLC.
Below is a verbatim transcript generated by Faster-Whisper from an audio recording.
Your task is to correct acoustic mishearings, domain-specific homophones, and proper nouns using the following domain glossary:

### Domain Glossary & Homophone Rules:
{glossary_items}

### Critical Invariants:
1. DO NOT summarize, condense, or truncate the transcript.
2. STRICTLY preserve all original timestamps (e.g. [00:15 -> 00:22]) and speaker markers.
3. Only correct misheard phonetic homophones and domain terms (e.g. replace 'Paul Radnicki' with 'Pawel Rudnicki', 'socks' with 'SOX' when referring to Sarbanes-Oxley/finance, 'pause X BFF' with 'POSIX VFS', 'six id' with 'sys_id').
4. Return the complete aligned transcript formatted in clean GitHub Markdown.
"""

        t0 = time.time()
        response = client.models.generate_content(
            model="gemini-3.8-flash",
            contents=[prompt, raw_text]
        )
        elapsed = time.time() - t0

        aligned_text = response.text.strip() if response.text else raw_text
        aligned_output_path.write_text(aligned_text, encoding="utf-8")

        print(f"✓ Aligned transcript generated in {elapsed:.2f}s")
        print(f"💾 Aligned output saved to: {aligned_output_path}")

        # Print entity corrections summary
        detect_and_print_corrections(raw_text, aligned_text, glossary)
        return True

    except Exception as e:
        print(f"⚠️ Warning: Tier 2 alignment skipped or throttled ({e}).")
        print(f"ℹ️ Raw Whisper transcript remains fully intact at: {raw_transcript_path}")
        aligned_output_path.write_text(raw_text, encoding="utf-8")
        return False

def detect_and_print_corrections(raw_text: str, aligned_text: str, glossary: dict):
    """Detects and prints entities that were successfully corrected."""
    print("-" * 70)
    print("🔍 Entity Alignment Receipts:")
    found_any = False
    for entity in glossary.keys():
        if entity in aligned_text and entity not in raw_text:
            print(f"  • Corrected domain entity: -> '{entity}'")
            found_any = True
    if not found_any:
        print("  • Verbatim alignment confirmed (no acoustic entity deviations detected).")
    print("-" * 70)

def main():
    parser = argparse.ArgumentParser(description="StackLabs 2-Tier Hybrid Transcriber & Entity Alignment Engine")
    parser.add_argument("audio", help="Path to input audio file on Clio (or existing transcript if --align-only)")
    parser.add_argument("--output", "-o", help="Path to aligned markdown output")
    parser.add_argument("--raw-output", help="Path to raw whisper markdown output")
    parser.add_argument("--model", "-m", default="base.en", help="Whisper model (default: base.en)")
    parser.add_argument("--compute", "-c", default="int8_float32", help="Compute type (default: int8_float32)")
    parser.add_argument("--align-only", action="store_true", help="Skip Tier 1 and perform Tier 2 alignment on existing markdown transcript")
    parser.add_argument("--skip-cloud-align", action="store_true", help="Perform Tier 1 Faster-Whisper only, skipping cloud alignment")
    args = parser.parse_args()

    input_path = Path(args.audio).resolve()
    if not input_path.exists():
        print(f"Error: Input file does not exist: {input_path}", file=sys.stderr)
        sys.exit(1)

    if args.align_only:
        raw_path = input_path
        aligned_path = Path(args.output).resolve() if args.output else input_path.parent / f"{input_path.stem}_aligned.md"
        success = run_tier2_semantic_alignment(raw_path, aligned_path)
        sys.exit(0 if success else 1)

    raw_path = Path(args.raw_output).resolve() if args.raw_output else input_path.parent / f"{input_path.stem}_raw_transcript.md"
    aligned_path = Path(args.output).resolve() if args.output else input_path.parent / f"{input_path.stem}_aligned_transcript.md"

    # Step 1: Tier 1 Artemis CUDA Whisper
    t1_ok = run_tier1_whisper(input_path, raw_path, model=args.model, compute=args.compute)
    if not t1_ok:
        print("❌ Error: Tier 1 Faster-Whisper failed on Artemis.", file=sys.stderr)
        sys.exit(1)

    # Step 2: Tier 2 Gemini 3.8 Flash Alignment
    if args.skip_cloud_align:
        print("ℹ️ Skipping Tier 2 cloud alignment (--skip-cloud-align specified).")
        aligned_path.write_text(raw_path.read_text(encoding="utf-8"), encoding="utf-8")
        sys.exit(0)

    run_tier2_semantic_alignment(raw_path, aligned_path)
    print("\n✅ Hybrid pipeline execution complete.")

if __name__ == "__main__":
    main()
