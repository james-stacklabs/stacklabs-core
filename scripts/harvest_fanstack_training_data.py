def sanitize_text(text: Optional[str]) -> str:
    """Cleans text of non-printable control characters, extraneous escapes, and whitespace."""
    if not text:
        return ""
    # Strip non-printable ascii except standard whitespace
    cleaned = "".join(ch for ch in text if ch.isprintable() or ch in "\n\t ")
    return " ".join(cleaned.split())


def load_persona_registry(conn: sqlite3.Connection) -> Dict[str, Dict[str, Any]]:
    """Loads all personas and their system instructions from the persona table."""
    cur = conn.cursor()
    cur.execute("""
        SELECT sys_id, user_name, display_name, team, system_prompt, 
               deep_lore, visual_style, behavior_notes, is_heel, rivalry_target_handle
        FROM persona
    """)
    personas = {}
    for row in cur.fetchall():
        u_name = str(row["user_name"]).strip().lower().lstrip("@")
        sys_prompt = row["system_prompt"]
        if not sys_prompt or len(sys_prompt.strip()) < 10:
            # Build high-fidelity fallback system prompt from deep lore & behavior notes
            disp = row["display_name"] or u_name
            team = row["team"] or "MLB"
            lore = row["deep_lore"] or "Passionate advocate."
            behavior = row["behavior_notes"] or ""
            sys_prompt = (
                f"You are @{u_name} ({disp}), an authentic, diehard {team} fan advocate "
                f"in the Sovereign OS FanStack stadium chat room. {lore} {behavior}".strip()
            )

        personas[u_name] = {
            "sys_id": row["sys_id"],
            "user_name": u_name,
            "display_name": row["display_name"] or u_name,
            "team": row["team"] or "MLB",
            "system_prompt": sys_prompt.strip(),
            "deep_lore": row["deep_lore"] or "",
            "is_heel": bool(row["is_heel"]),
            "rivalry_target": row["rivalry_target_handle"] or ""
        }
    logger.info("Loaded %d personas from master registry.", len(personas))
    return personas


def load_game_metadata(conn: sqlite3.Connection) -> Dict[str, Dict[str, Any]]:
    """Loads game schedule metadata keyed by string game_pk."""
    cur = conn.cursor()
    cur.execute("SELECT game_pk, game_date, away_team, home_team, venue, status FROM mlb_schedule")
    games = {}
    for row in cur.fetchall():
        pk = str(row["game_pk"])
        games[pk] = {
            "game_pk": pk,
            "game_date": row["game_date"] or "Unknown Date",
            "away_team": row["away_team"] or "AWAY",
            "home_team": row["home_team"] or "HOME",
            "venue": row["venue"] or "Ballpark",
            "status": row["status"] or "Final"
        }
    return games


def load_game_plays(conn: sqlite3.Connection, game_pk: str) -> List[Dict[str, Any]]:
    """Loads chronological plays for a game from game_play and statcast_pitches."""
    cur = conn.cursor()
    plays = []
    
    # Try game_play first
    try:
        cur.execute("""
            SELECT play_id, inning, half, event_type, batter, pitcher, pitch_speed, pitch_type,
                   description, score_away, score_home, outs, recorded_at
            FROM game_play
            WHERE game_pk = ?
            ORDER BY recorded_at ASC
        """, (game_pk,))
        for r in cur.fetchall():
            plays.append({
                "play_id": r["play_id"] or "",
                "inning": r["inning"] or 1,
                "half": r["half"] or "top",
                "event_type": r["event_type"] or "play",
                "batter": r["batter"] or "",
                "pitcher": r["pitcher"] or "",
                "pitch_speed": r["pitch_speed"],
                "pitch_type": r["pitch_type"] or "",
                "description": r["description"] or "",
                "score_away": r["score_away"] or 0,
                "score_home": r["score_home"] or 0,
                "outs": r["outs"] or 0,
                "timestamp": r["recorded_at"] or ""
            })
    except Exception as e:
        logger.debug("Querying game_play for game %s had issue: %s", game_pk, e)

    # If game_play was empty, fall back to statcast_pitches
    if not plays:
        try:
            cur.execute("""
                SELECT at_bat_number, pitch_number, events, description, des,
                       away_score, home_score, inning, outs_when_up, balls, strikes,
                       pitch_name, release_speed, batter, pitcher
                FROM statcast_pitches
                WHERE game_pk = ?
                ORDER BY at_bat_number ASC, pitch_number ASC
            """, (game_pk,))
            for r in cur.fetchall():
                desc = r["des"] or r["description"] or r["events"] or "Pitch"
                plays.append({
                    "play_id": f"{r['at_bat_number']}_{r['pitch_number']}",
                    "inning": r["inning"] or 1,
                    "half": "top",
                    "event_type": r["events"] or "pitch",
                    "batter": str(r["batter"] or ""),
                    "pitcher": str(r["pitcher"] or ""),
                    "pitch_speed": r["release_speed"],
                    "pitch_type": r["pitch_name"] or "",
                    "description": desc,
                    "score_away": r["away_score"] or 0,
                    "score_home": r["home_score"] or 0,
                    "outs": r["outs_when_up"] or 0,
                    "timestamp": ""
                })
        except Exception as e:
            logger.debug("Querying statcast_pitches for game %s had issue: %s", game_pk, e)

    return plays


def find_active_play_context(plays: List[Dict[str, Any]], msg_time: str, game_meta: Dict[str, Any]) -> str:
    """Constructs situational context string for a chat turn."""
    away = game_meta.get("away_team", "AWAY")
    home = game_meta.get("home_team", "HOME")
    venue = game_meta.get("venue", "Citi Field")

    if not plays:
        return f"[GAME CONTEXT: {away} @ {home} ({venue}) | Live Game Action]"

    # If plays have timestamps, find nearest preceding play
    target_play = plays[-1]
    if msg_time:
        for p in reversed(plays):
            p_ts = p.get("timestamp")
            if p_ts and p_ts <= msg_time:
                target_play = p
                break

    desc = target_play.get("description", "In play")
    inn = target_play.get("inning", 1)
    half = target_play.get("half", "top")
    outs = target_play.get("outs", 0)
    score_a = target_play.get("score_away", 0)
    score_h = target_play.get("score_home", 0)
    speed = target_play.get("pitch_speed")
    ptype = target_play.get("pitch_type")
    
    parts = [f"[STATCAST: Inning {inn} {half.upper()}, {outs} Outs | Score: {away} {score_a} - {home} {score_h}"]
    if speed and ptype:
        parts.append(f"| Pitch: {speed} mph {ptype}")
    if desc:
        parts.append(f"| Event: \"{desc}\"")
    parts.append("]")
    return " ".join(parts)


def harvest_dataset(
    out_dir: str,
    sync_dir: str,
    min_turns: int = 10000,
    limit_games: Optional[int] = None,
    generate_dpo: bool = True
) -> Dict[str, Any]:
    """Executes the full extraction, transformation, and packaging pipeline."""
    os.makedirs(out_dir, exist_ok=True)
    os.makedirs(sync_dir, exist_ok=True)

    raw_path = os.path.join(out_dir, "fanstack_season_raw.jsonl")
    sft_path = os.path.join(out_dir, "fanstack_sft_dolphin.jsonl")
    dpo_path = os.path.join(out_dir, "fanstack_dpo_pairs.jsonl")

    logger.info("Harvesting FanStack telemetry corpus from database: %s", DB_PATH)
    
    with get_db(row_factory=True, timeout=60.0) as conn:
        personas = load_persona_registry(conn)
        game_meta = load_game_metadata(conn)

        # Query all games that have chat messages
        cur = conn.cursor()
        cur.execute("""
            SELECT game_pk, COUNT(id) as msg_count, MIN(created_at) as min_ts, MAX(created_at) as max_ts
            FROM game_chat
            GROUP BY game_pk
            ORDER BY msg_count DESC
        """)
        game_rows = cur.fetchall()
        if limit_games:
            game_rows = game_rows[:limit_games]

        logger.info("Found %d distinct games with chat records to process.", len(game_rows))

        raw_count = 0
        sft_count = 0
        dpo_count = 0
        persona_counts: Dict[str, int] = {}
        token_lengths: List[int] = []

        with open(raw_path, "w", encoding="utf-8") as f_raw, \
             open(sft_path, "w", encoding="utf-8") as f_sft, \
             open(dpo_path, "w", encoding="utf-8") as f_dpo:

            for idx, g_row in enumerate(game_rows, 1):
                g_pk = str(g_row["game_pk"])
                g_meta = game_meta.get(g_pk, {
                    "game_pk": g_pk, "game_date": "2026-05-01",
                    "away_team": "AWAY", "home_team": "NYM", "venue": "Citi Field"
                })
                
                plays = load_game_plays(conn, g_pk)

                # Fetch chronological messages for this game
                cur.execute("""
                    SELECT id, game_pk, persona, msg_type, text, model, created_at
                    FROM game_chat
                    WHERE game_pk = ?
                    ORDER BY created_at ASC
                """, (g_pk,))
                messages = cur.fetchall()

                # Sliding window of dialogue history
                dialogue_history: List[Tuple[str, str]] = []  # (persona, clean_text)
                
                # Group for DPO pairing within the game
                recent_reactions: List[Dict[str, Any]] = []

                for m in messages:
                    text = sanitize_text(m["text"])
                    if not text or len(text) < 3:
                        continue
                    
                    p_handle = str(m["persona"]).strip().lower().lstrip("@")
                    p_info = personas.get(p_handle)
                    if not p_info:
                        # Auto-synthesize profile for ad-hoc or guest handles
                        p_info = {
                            "user_name": p_handle,
                            "display_name": p_handle.capitalize(),
                            "team": g_meta.get("home_team", "NYM"),
                            "system_prompt": f"You are @{p_handle}, a lively baseball fan in the stadium chatroom.",
                            "deep_lore": "Passionate fan.",
                            "is_heel": False,
                            "rivalry_target": ""
                        }

                    ts = m["created_at"] or ""
                    raw_record = {
                        "id": m["id"],
                        "game_pk": g_pk,
                        "persona": p_handle,
                        "display_name": p_info["display_name"],
                        "team": p_info["team"],
                        "text": text,
                        "model": m["model"] or "gemini-3.8-flash",
                        "created_at": ts,
                        "game_date": g_meta.get("game_date")
                    }
                    f_raw.write(json.dumps(raw_record) + "\n")
                    raw_count += 1

                    # ── Format ChatML SFT Turn ─────────────────────────────────
                    play_ctx = find_active_play_context(plays, ts, g_meta)
                    
                    # Construct realistic conversational prompt with micro-context (1-2 prior messages)
                    user_turns = [play_ctx]
                    if dialogue_history:
                        # Last 1-2 other speaker messages
                        prior = dialogue_history[-2:]
                        prior_formatted = "\n".join([f"@{u}: \"{t}\"" for u, t in prior if u != p_handle])
                        if prior_formatted:
                            user_turns.append(f"Room Banter:\n{prior_formatted}")
                    
                    user_prompt = "\n\n".join(user_turns)
                    
                    sft_entry = {
                        "messages": [
                            {"role": "system", "content": p_info["system_prompt"]},
                            {"role": "user", "content": user_prompt},
                            {"role": "assistant", "content": text}
                        ],
                        "metadata": {
                            "game_pk": g_pk,
                            "persona": p_handle,
                            "timestamp": ts,
                            "char_count": len(text)
                        }
                    }
                    f_sft.write(json.dumps(sft_entry) + "\n")
                    sft_count += 1

                    persona_counts[p_handle] = persona_counts.get(p_handle, 0) + 1
                    token_lengths.append(len(text.split()))

                    # ── DPO Pairing ───────────────────────────────────────────
                    if generate_dpo:
                        recent_reactions.append({
                            "persona": p_handle,
                            "is_heel": p_info["is_heel"],
                            "text": text,
                            "prompt": play_ctx,
                            "ts": ts
                        })
                        # Once we have 2 contrasting reactions in the buffer, emit DPO pair
                        if len(recent_reactions) >= 2:
                            r1, r2 = recent_reactions[-2], recent_reactions[-1]
                            if r1["persona"] != r2["persona"]:
                                # Select chosen vs rejected based on fan alignment vs heel/neutral
                                if r2["is_heel"] and not r1["is_heel"]:
                                    chosen, rejected = r1["text"], r2["text"]
                                    c_p, r_p = r1["persona"], r2["persona"]
                                else:
                                    chosen, rejected = r2["text"], r1["text"]
                                    c_p, r_p = r2["persona"], r1["persona"]

                                dpo_entry = {
                                    "prompt": r2["prompt"],
                                    "chosen": chosen,
                                    "rejected": rejected,
                                    "persona_chosen": c_p,
                                    "persona_rejected": r_p,
                                    "game_pk": g_pk
                                }
                                f_dpo.write(json.dumps(dpo_entry) + "\n")
                                dpo_count += 1

                    # Update history
                    dialogue_history.append((p_handle, text))
                    if len(dialogue_history) > 4:
                        dialogue_history.pop(0)

                if idx % 25 == 0 or idx == len(game_rows):
                    logger.info("Processed %d/%d games | Cumulative SFT Turns: %d | DPO Pairs: %d",
                                idx, len(game_rows), sft_count, dpo_count)

    # Copy generated artifacts to sync_dir for colab-mcp staging
    for filename in ["fanstack_season_raw.jsonl", "fanstack_sft_dolphin.jsonl", "fanstack_dpo_pairs.jsonl"]:
        src = os.path.join(out_dir, filename)
        dst = os.path.join(sync_dir, filename)
        if os.path.exists(src):
            shutil.copy2(src, dst)
            logger.info("Synced %s -> %s", filename, sync_dir)

    avg_tokens = sum(token_lengths) / len(token_lengths) if token_lengths else 0
    results = {
        "raw_messages_extracted": raw_count,
        "sft_turns_generated": sft_count,
        "dpo_pairs_generated": dpo_count,
        "distinct_personas": len(persona_counts),
        "top_personas": sorted(persona_counts.items(), key=lambda x: x[1], reverse=True)[:10],
        "avg_words_per_turn": round(avg_tokens, 2),
        "target_met": sft_count >= min_turns,
        "raw_path": raw_path,
        "sft_path": sft_path,
        "dpo_path": dpo_path,
        "sync_dir": sync_dir
    }
    return results


def validate_dataset(sft_path: str, dpo_path: str) -> bool:
    """Validates schema structure, json encoding, and role integrity."""
    logger.info("Validating SFT ChatML schema on: %s", sft_path)
    sft_valid = 0
    with open(sft_path, "r", encoding="utf-8") as f:
        for idx, line in enumerate(f, 1):
            data = json.loads(line)
            assert "messages" in data, f"Missing 'messages' at line {idx}"
            msgs = data["messages"]
            assert len(msgs) == 3, f"Expected 3 messages (sys, user, assistant) at line {idx}"
            assert msgs[0]["role"] == "system"
            assert msgs[1]["role"] == "user"
            assert msgs[2]["role"] == "assistant"
            assert len(msgs[0]["content"]) > 0
            assert len(msgs[1]["content"]) > 0
            assert len(msgs[2]["content"]) > 0
            sft_valid += 1

    logger.info("✅ SFT ChatML Validation Passed: %d valid rows.", sft_valid)

    if os.path.exists(dpo_path):
        dpo_valid = 0
        with open(dpo_path, "r", encoding="utf-8") as f:
            for idx, line in enumerate(f, 1):
                data = json.loads(line)
                assert "prompt" in data and "chosen" in data and "rejected" in data
                dpo_valid += 1
        logger.info("✅ DPO Validation Passed: %d valid pairs.", dpo_valid)

    return True


